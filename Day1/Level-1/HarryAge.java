class HarryAge {
    public static void main(String[] args){
       
        //Name of the Person
        String name = "Harry";
       
        //Person's Birth Year and Current Year
        int birthYear = 2000, presentYear = 2024;
       
        //Age of the Person
        int age = (presentYear - birthYear);
       
        System.out.println(name + "'s age in " + presentYear + " is " + age);
       
    }
}